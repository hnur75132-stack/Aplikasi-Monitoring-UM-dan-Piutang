/**
 * Helper to compute matrix totals row
 */
export function calculateRSBMatrixTotals(rows: RSBMatrixRow[]) {
  const totalPKS = rows.reduce((acc, r) => acc + r.totalDanaPKS, 0);
  const totalPencairan = rows.reduce((acc, r) => acc + r.totalDanaPencairan, 0);
  const totalT1 = rows.reduce((acc, r) => acc + (r.tahap1?.nominal || 0), 0);
  const totalT2 = rows.reduce((acc, r) => acc + (r.tahap2?.nominal || 0), 0);
  const totalT3 = rows.reduce((acc, r) => acc + (r.tahap3?.nominal || 0), 0);
  const totalT4 = rows.reduce((acc, r) => acc + (r.tahap4?.nominal || 0), 0);
  const totalT5 = rows.reduce((acc, r) => acc + (r.tahap5?.nominal || 0), 0);
  const totalT6 = rows.reduce((acc, r) => acc + (r.tahap6?.nominal || 0), 0);
  const totalJumlah = rows.reduce((acc, r) => acc + r.jumlah, 0);
  const totalSisa = rows.reduce((acc, r) => acc + r.sisa, 0);
  const persentaseTotal = totalPKS > 0 ? (totalJumlah / totalPKS) * 100 : 0;

  return {
    totalPKS,
    totalPencairan,
    totalT1,
    totalT2,
    totalT3,
    totalT4,
    totalT5,
    totalT6,
    totalJumlah,
    totalSisa,
    persentaseTotal,
  };
}
